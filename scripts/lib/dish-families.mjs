// MC-085 — dish blueprint families for the generation pipeline
// (PLAN-2000-RECIPES.md §5.3).
//
// Family schema:
//   cat, n        — dish category and how many cards the family yields
//   mealTypes, cuisine?, appl?
//   slots         — { key: ['role1','role2'] } or { key: {fixed:[names]} };
//                   the engine resolves each slot to a pool and walks the
//                   cartesian product deterministically
//   title(s)      — natural Russian title built from resolved items
//   build(s, int) — { prep, cook, steps[] }; int(lo, hi) is the seeded rng
//
// Every ingredient name comes from WF (dish-blueprints.mjs), so all case
// forms used in titles and steps are hand-curated, not guessed.

import { WF } from './dish-blueprints.mjs';

const W = (name) => ({ name, ...WF[name] });

export const FAMILIES = [];

function addFamily(f) {
  FAMILIES.push(f);
}

